JT_TEST(abi_user_library_packs_capabilities_as_the_kernel_does)
{
    /* J_CAPS1 and the kernel's unpacking agree, and so do the readers. */
    struct joist_msg m;
    abi_caps_unpack(J_CAPS1(37, J_R_SEND), &m);
    JT_CHECK(m.ncaps == 1 && m.cap[0] == 37 && m.mask[0] == JOIST_R_SEND);
    struct joist_msg got = {0};
    got.ncaps = 2;
    got.cap[0] = 9;
    got.cap[1] = JOIST_SLOT_NONE;
    uint64_t packed = abi_caps_pack(&got);
    JT_CHECK(J_CAPS_COUNT(packed) == 2 && J_CAPS_SLOT(packed, 0) == 9 &&
             J_CAPS_SLOT(packed, 1) == 0xffffu);
}
