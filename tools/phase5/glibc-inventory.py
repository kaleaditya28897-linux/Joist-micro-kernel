"""glibc-inventory.py - Phase 5 step 5, decision 0031's check: what the reused
Hurd code reaches in glibc, and what of that stands on Mach.

Input: the lld --why-extract files of static links (tools/phase5/glibc-inventory.sh
makes them), the sysroot's archives, and glibc's source file list. Every archive
member a link pulls in is classified by where its source is:

  mach      glibc's Mach layer: mach/, sysdeps/mach/ (not sysdeps/mach/hurd),
            the kernel's MIG stubs (libmachuser, syscall_*): what sysdeps/joist
            replaces
  hurd      glibc's Hurd layer: hurd/, sysdeps/mach/hurd/: kept (0031)
  htl       glibc's threads for the Hurd: htl/, sysdeps/htl, .../htl
  hurd-rpc  MIG user stubs to Hurd servers (libhurduser): regenerated by
            Joist's MIG backend
  generic   the rest of libc: needs nothing of Joist
  hurd-lib  the reused Hurd libraries (libports, libtrivfs, ...)
  gcc       libgcc

and, for each member outside the Mach layer, the Mach-layer symbols it uses
directly: the interface sysdeps/joist must provide.

usage: glibc-inventory.py OUTDIR SYSROOT GLIBC_FILES WHY...
"""
import collections
import csv
import os
import re
import subprocess
import sys

out, sysroot, files_list = sys.argv[1], sys.argv[2], sys.argv[3]
whys = sys.argv[4:]

# ---- members reached, per program ----
reached = collections.defaultdict(set)  # (archive, member) -> programs
for w in whys:
    prog = os.path.basename(w).removesuffix(".why")
    with open(w) as f:
        next(f)
        for line in f:
            m = re.search(r"([^/\t]+\.a)\(([^)]+)\)\t[^\t]*$", line)
            if m:
                reached[(m.group(1), m.group(2))].add(prog)
            ex = line.split("\t")[1]
            m = re.search(r"([^/]+\.a)\(([^)]+)\)$", ex)
            if m:
                reached[(m.group(1), m.group(2))].add(prog)

# ---- every member's symbols ----
defs = collections.defaultdict(set)   # (archive, member) -> defined
undefs = collections.defaultdict(set)  # (archive, member) -> undefined
archives = sorted({a for a, _ in reached})
paths = {}
for root, _, fs in os.walk(sysroot):
    for f in fs:
        if f in archives:
            paths[f] = os.path.join(root, f)
for a in archives:
    r = subprocess.run(["nm", "-A", paths[a]], capture_output=True, text=True)
    for line in r.stdout.splitlines():
        m = re.match(r"[^:]*:([^:]+):\s*(?:[0-9a-f]+)?\s+(\w)\s+(\S+)$", line)
        if not m:
            continue
        member, kind, sym = m.groups()
        (undefs if kind in "Uw" else defs)[(a, member)].add(sym) if kind != "w" else None

# ---- where each libc member's source is ----
sources = collections.defaultdict(list)  # stem -> paths
with open(files_list) as f:
    for p in f:
        p = p.strip().split("/", 1)[-1]
        b = os.path.basename(p)
        stem, ext = os.path.splitext(b)
        if ext in (".c", ".S", ".s"):
            sources[stem].append(p)

ORDER = ["sysdeps/mach/hurd/x86_64/htl", "sysdeps/mach/hurd/x86_64", "sysdeps/mach/hurd/x86/htl",
         "sysdeps/mach/hurd/x86", "sysdeps/mach/hurd/htl", "sysdeps/mach/hurd", "sysdeps/mach/x86_64",
         "sysdeps/mach/x86", "sysdeps/mach/htl", "sysdeps/mach", "sysdeps/x86_64/htl", "sysdeps/x86/htl",
         "sysdeps/htl", "sysdeps/pthread", "sysdeps/x86_64/fpu", "sysdeps/x86_64", "sysdeps/x86/fpu",
         "sysdeps/x86", "sysdeps/ieee754/ldbl-96", "sysdeps/ieee754/dbl-64", "sysdeps/ieee754/flt-32",
         "sysdeps/ieee754", "sysdeps/wordsize-64", "sysdeps/posix", "sysdeps/generic"]


def source_of(member):
    stem = os.path.splitext(member)[0]
    cands = sources.get(stem, [])
    for d in ORDER:
        for c in cands:
            if os.path.dirname(c) == d:
                return c
    for c in cands:
        if not c.startswith("sysdeps/"):
            return c
    for c in cands:  # an x86 variant (multiarch string functions and the like)
        if c.startswith("sysdeps/x86"):
            return c
    return ""


def category(a, member, src):
    if a == "libmachuser.a":
        return "mach"
    if a == "libhurduser.a":
        return "hurd-rpc"
    if a in ("libgcc.a", "libgcc_eh.a"):
        return "gcc"
    if a != "libcrt.a":
        return "hurd-lib"
    if src == "":
        # Generated: the kernel's stubs built into libc (mach/: syscall_*,
        # mach_*, or anything calling mach_msg), or other generated C.
        u = undefs[(a, member)]
        if member.startswith(("syscall_", "mach_")) or u & {"__mach_msg", "__mach_msg_trap", "mach_msg"}:
            return "mach"
        return "generic"
    if "/htl" in "/" + src or src.startswith("htl/"):
        return "htl"
    if src.startswith("sysdeps/mach/hurd/") or src.startswith("hurd/"):
        return "hurd"
    if src.startswith("sysdeps/mach/") or src.startswith("mach/"):
        return "mach"
    return "generic"


rows = []
cat = {}
for (a, member), progs in sorted(reached.items()):
    src = source_of(member) if a == "libcrt.a" else ""
    c = category(a, member, src)
    cat[(a, member)] = c
    rows.append([a, member, src, c, " ".join(sorted(progs))])

# Mach-layer symbols, and who outside the layer uses them directly.
mach_defs = {}
for k, c in cat.items():
    if c == "mach":
        for s in defs[k]:
            mach_defs.setdefault(s, k)
users = collections.defaultdict(set)  # mach symbol -> members using it
for k, c in cat.items():
    if c != "mach":
        for s in undefs[k]:
            if s in mach_defs:
                users[s].add(k[1] + " (" + c + ")")
for r in rows:
    k = (r[0], r[1])
    r.append(" ".join(sorted(s for s in undefs[k] if s in mach_defs)) if cat[k] != "mach" else "")

os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "members.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["archive", "member", "glibc source", "class", "programs", "Mach symbols used directly"])
    w.writerows(rows)
with open(os.path.join(out, "mach-interface.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["Mach-layer symbol", "defined in", "users outside the Mach layer"])
    for s in sorted(users):
        w.writerow([s, mach_defs[s][1], " ".join(sorted(users[s]))])

counts = collections.Counter(cat.values())
direct = collections.Counter(cat[(r[0], r[1])] for r in rows if r[5])
print("members reached:", len(rows))
for c in ("mach", "hurd", "htl", "hurd-rpc", "generic", "hurd-lib", "gcc"):
    print(f"  {c:9} {counts[c]:4}   of them using the Mach layer directly: {direct[c]}")
print("Mach-layer symbols used from outside it:", len(users))
